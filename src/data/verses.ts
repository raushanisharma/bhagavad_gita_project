export const verseById = new Map(verses.map((v) => [v.id, v]));

export function getVerse(id: string): Verse | undefined {
  return verseById.get(id);
}

export function versesForMood(mood: string): Verse[] {
  return verses.filter((v) => v.moods.includes(mood as Verse["moods"][number]));
}

export function versesForChapter(chapter: number): Verse[] {
  return verses.filter((v) => v.chapter === chapter);
}

/** Deterministic "verse of the day" based on the local calendar date. */
export function verseOfTheDay(date: Date): Verse {
  const dayNumber = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000,
  );
  return verses[dayNumber % verses.length];
}
